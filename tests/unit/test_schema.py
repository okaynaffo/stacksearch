def test_pack_unpack_roundtrip():
    values = [0.5, -0.25, 1.0, 0.0]
    blob = pack_embedding(values)
    assert len(blob) == 4 * len(values)
    assert unpack_embedding(blob) == pytest.approx(tuple(values))


def test_upsert_vector_and_knn(tmp_path):
    """A stored vector must be findable by exact match at distance 0."""
    with open_index(tmp_path / "index.db") as ix:
        ix.conn.execute(
            "INSERT INTO sources(kind, name, config_json) VALUES ('files', 't', '{}')"
        )
        src = ix.conn.execute("SELECT last_insert_rowid()").fetchone()[0]
        ix.conn.execute(
            "INSERT INTO documents(source_id, external_id, uri, content_hash)"
            " VALUES (?, ?, ?, ?)",
            (src, "/a.md", "file:///a.md", "h1"),
        )
        doc = ix.conn.execute("SELECT last_insert_rowid()").fetchone()[0]
        ix.conn.execute(
            "INSERT INTO chunks(document_id, ord, text, chunk_hash, loc_json, token_count)"
            " VALUES (?, ?, ?, ?, ?, ?)",
            (doc, 0, "hello world", "ch1", "{}", 3),
        )
        chunk = ix.conn.execute("SELECT last_insert_rowid()").fetchone()[0]

        upsert_vector(ix.conn, chunk, [0.1] * 768)

        row = ix.conn.execute(
            "SELECT chunk_id, distance FROM chunks_vec"
            " WHERE embedding MATCH ? AND k = 1",
            (pack_embedding([0.1] * 768),),
        ).fetchone()
        assert row["chunk_id"] == chunk
        assert row["distance"] == pytest.approx(0.0, abs=1e-5)


def test_upsert_vector_replaces_rather_than_duplicates(tmp_path):
    with open_index(tmp_path / "index.db") as ix:
        upsert_vector(ix.conn, 1, [0.0] * 768)
        upsert_vector(ix.conn, 1, [0.5] * 768)
        assert ix.conn.execute("SELECT COUNT(*) FROM chunks_vec").fetchone()[0] == 1


def test_wrong_width_vector_is_rejected(tmp_path):
    """vec0 must refuse a mismatched width rather than silently storing garbage."""
    with open_index(tmp_path / "index.db") as ix:
        with pytest.raises(sqlite3.OperationalError):
            ix.conn.execute(
                "INSERT INTO chunks_vec(chunk_id, embedding) VALUES (?, ?)",
                (1, pack_embedding([0.1] * 384)),
            )


