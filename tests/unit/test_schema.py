def test_no_literal_float_dim_in_source_tree():
    """``FLOAT[...]`` may only appear inside ``chunks_vec_ddl``.

    PLAN.md §5: "The vector dimension is never hardcoded... generated by the migration
    layer from meta.embedding_dim, never hand-written." This is the test that stops a
    future edit from quietly reintroducing a fixed-width table.

    Walks the AST rather than grepping lines, so prose in docstrings and comments that
    *mentions* ``FLOAT[768]`` (as this file does) is not a false positive — only a string
    literal that would actually be handed to SQLite counts.
    """
    import core.index as index_pkg

    allowed_fn = "chunks_vec_ddl"
    offenders: list[str] = []

    for path in sorted(pathlib.Path(index_pkg.__file__).parent.rglob("*.py")):
        tree = ast.parse(path.read_text())
        for node, in_allowed in _walk(tree, allowed_fn):
            if in_allowed:
                continue
            if _declares_float_dim(node):
                offenders.append(f"{path.name}:{getattr(node, 'lineno', '?')}")

    assert not offenders, (
        f"literal FLOAT[n] outside {allowed_fn}() at {offenders} "
        "(PLAN.md §5 requires the width to come from meta.embedding_dim)"
    )


def _walk(node: ast.AST, allowed_fn: str, in_allowed: bool = False):
    """Yield ``(node, is_inside_allowed_fn)``, skipping docstrings.

    Docstrings are prose: several of them *describe* the ``FLOAT[n]`` rule, and
    counting them would make this test fail on its own explanation.
    """
    docstring = None
    if isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
        docstring = ast.get_docstring(node, clean=False)

    for child in ast.iter_child_nodes(node):
        if isinstance(child, ast.Expr) and docstring is not None:
            inner = child.value
            if isinstance(inner, ast.Constant) and inner.value == docstring:
                continue
        child_allowed = in_allowed or (
            isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef))
            and child.name == allowed_fn
        )
        yield child, child_allowed
        yield from _walk(child, allowed_fn, child_allowed)


def _declares_float_dim(node: ast.AST) -> bool:
    """True if this node is a string literal declaring a vec0 ``FLOAT[n]`` column."""
    if isinstance(node, ast.JoinedStr):
        # f-string: only literal (non-interpolated) fragments can hardcode a width.
        return any(
            "FLOAT[" in v.value
            for v in node.values
            if isinstance(v, ast.Constant) and isinstance(v.value, str)
        )
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return "FLOAT[" in node.value and "vec0" in node.value
    return False


