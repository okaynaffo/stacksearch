def _seed_chunks(ix, n: int = 5) -> list[int]:
    ix.conn.execute("INSERT INTO sources(kind, name, config_json) VALUES ('files', 't', '{}')")
    src = ix.conn.execute("SELECT last_insert_rowid()").fetchone()[0]
    ids = []
    for i in range(n):
        ix.conn.execute(
            "INSERT INTO documents(source_id, external_id, uri, content_hash, status)"
            " VALUES (?, ?, ?, ?, 'indexed')",
            (src, f"/{i}.md", f"file:///{i}.md", f"h{i}"),
        )
        doc = ix.conn.execute("SELECT last_insert_rowid()").fetchone()[0]
        ix.conn.execute(
            "INSERT INTO chunks(document_id, ord, text, chunk_hash, loc_json, token_count)"
            " VALUES (?, ?, ?, ?, ?, ?)",
            (doc, 0, f"chunk {i}", f"c{i}", "{}", 3),
        )
        cid = ix.conn.execute("SELECT last_insert_rowid()").fetchone()[0]
        upsert_vector(ix.conn, cid, [0.1] * 768)
        ids.append(cid)
    return ids


def test_dimension_change_rebuilds_and_requeues(tmp_path):
    path = tmp_path / "index.db"
    with open_index(path) as ix:
        chunk_ids = _seed_chunks(ix)

    # Switch to the 384d ablation arm from §14.3.
    small = EMBEDDING_MODELS["bge-small-en-v1.5"]
    with open_index(path, model=small) as ix:
        assert ix.embedding_dim == 384
        assert ix.reconcile_report["dim_changed"] is True
        assert ix.reconcile_report["model_changed"] is True
        assert ix.reconcile_report["requeued_chunks"] == len(chunk_ids)

        # Vector table was rebuilt at the new width...
        assert vector_index_dim(ix.conn) == 384
        assert ix.conn.execute("SELECT COUNT(*) FROM chunks_vec").fetchone()[0] == 0
        # ...while chunks and their hashes survive, awaiting re-embed.
        assert ix.conn.execute("SELECT COUNT(*) FROM chunks").fetchone()[0] == len(chunk_ids)

        queued = ix.conn.execute(
            "SELECT payload_json, priority FROM jobs WHERE kind = 'reembed'"
        ).fetchall()
        assert len(queued) == len(chunk_ids)
        assert all(row["priority"] == 2 for row in queued)


def test_rebuild_skips_soft_deleted_documents(tmp_path):
    path = tmp_path / "index.db"
    with open_index(path) as ix:
        ids = _seed_chunks(ix, n=4)
        # Soft-delete one document the way §6.5.3 does.
        ix.conn.execute(
            "UPDATE documents SET status = 'deleted' WHERE id ="
            " (SELECT document_id FROM chunks WHERE id = ?)",
            (ids[-1],),
        )

    small = EMBEDDING_MODELS["bge-small-en-v1.5"]
    with open_index(path, model=small) as ix:
        assert ix.reconcile_report["requeued_chunks"] == 3


def test_reconcile_is_a_noop_when_model_unchanged(tmp_path):
    path = tmp_path / "index.db"
    with open_index(path) as ix:
        _seed_chunks(ix, n=3)
    with open_index(path) as ix:
        report = ix.reconcile_report
        assert report["dim_changed"] is False
        assert report["requeued_chunks"] == 0
        assert ix.conn.execute("SELECT COUNT(*) FROM jobs").fetchone()[0] == 0


def test_model_change_same_dim_keeps_vectors(tmp_path):
    """A different 768d model still invalidates embeddings, so it must re-embed.

    §5 stores the model id alongside the dimension precisely because equal dimension
    does not mean equal vectors. The table is reused; the jobs are what force the
    re-computation.
    """
    path = tmp_path / "index.db"
    with open_index(path) as ix:
        _seed_chunks(ix, n=2)

    other = EMBEDDING_MODELS["bge-base-en-v1.5"]
    assert other.dim == EMBEDDING_MODELS["multilingual-e5-base"].dim
    with open_index(path, model=other) as ix:
        assert ix.reconcile_report["model_changed"] is True
        assert ix.reconcile_report["dim_changed"] is False


